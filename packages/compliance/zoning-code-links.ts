export function zoningCodeLinks(article: string | null, subdistrict: string) {
  // Article 13 contains the dimensional tables for these letter-designated underlying districts.
  const key = article === "Underlying Zoning" && /^(?:R-8|H-|[LBMI]-|MER-)/u.test(subdistrict)
    ? "13"
    : article?.trim().toUpperCase().replace(/^(?:ARTICLE|ART\.)\s+/u, "");
  const nodes = key && Object.hasOwn(codeNodes, key) ? codeNodes[key] : undefined;
  return {
    articleUrl: nodes ? `${bostonZoningCode}?nodeId=${nodes[0]}` : null,
    tablesUrl: nodes?.[1] ? `${bostonZoningCode}?nodeId=${nodes[1]}` : null,
  };
}
